#!/usr/bin/env bash
# SonicFX Media 4K Setup
# =====================
# Installs a free/open-source playback stack for smooth 4K movies and music:
#
#   * Intel VA-API hardware decoding (iHD driver) — HEVC/H.264/VP9 on HD 620
#   * mpv + Celluloid movie player, ffmpeg, GStreamer VA-API plugins
#   * Per-user mpv config tuned for film playback at up to 4K
#   * Optional VA-API prefs for Firefox (deb and snap profiles)
#
# Everything installed here is free of cost and open source (MIT/BSD/GPL/LGPL).
# No proprietary codec packs, no accounts, no telemetry.
#
# Usage:  sudo scripts/install-media-4k.sh
#
# Notes for Intel HD 620 (Kaby Lake) laptops:
#   - Hardware decode: H.264, VC-1, MPEG-2, HEVC 8/10-bit, VP9 8-bit.
#   - No AV1 hardware decode: 4K AV1 files will decode in software (may stutter).
#   - Internal panel resolution is unchanged; 4K video is downscaled smoothly.
#   - External output: HDMI 1.4 => 4K@30Hz max; USB-C/DP 1.2 => 4K@60Hz max.
set -euo pipefail

if [[ ${EUID} -ne 0 ]]; then
    echo "Please run as: sudo $0" >&2
    exit 1
fi

TARGET_USER="${SUDO_USER:-}"
if [[ -z ${TARGET_USER} || ${TARGET_USER} == root ]]; then
    echo "Run this via sudo from your normal user account." >&2
    echo "Example: sudo scripts/install-media-4k.sh" >&2
    exit 1
fi

TARGET_HOME="$(getent passwd "${TARGET_USER}" | cut -d: -f6)"
if [[ ! -d ${TARGET_HOME} ]]; then
    echo "Cannot resolve home directory for ${TARGET_USER}" >&2
    exit 1
fi
TARGET_GROUP="$(id -gn "${TARGET_USER}")"

say() { printf '\n>>> %s\n' "$*"; }

say "Updating package lists"
apt-get update -qq

# Core, fully free packages.
say "Installing free 4K media stack"
CORE_PKGS=(
    intel-media-va-driver     # iHD VA-API driver (MIT), Gen9.5 4K decode
    libva2
    libva-drm2
    mesa-va-drivers           # OpenGL/gallium VA-API fallback
    ffmpeg
    mpv
    yt-dlp                    # required by mpv for YouTube/URL playback
    celluloid                 # friendly GTK movie player built on mpv
    gstreamer1.0-vaapi
    gstreamer1.0-libav
    gstreamer1.0-plugins-good
    gstreamer1.0-plugins-bad
)
apt-get install -y --no-install-recommends "${CORE_PKGS[@]}"

# vainfo lives in libva-utils on most releases; the package name changed on
# some newer Ubuntu versions, so try both and never fail the whole script.
say "Installing VA-API inspection tool"
apt-get install -y --no-install-recommends libva-utils 2>/dev/null \
    || apt-get install -y --no-install-recommends vainfo 2>/dev/null \
    || echo "warning: no vainfo package found (optional)" >&2

# ---------------------------------------------------------------------------
# Per-user mpv configuration (movie-friendly, hardware decoded)
# ---------------------------------------------------------------------------
say "Writing mpv config for ${TARGET_USER}"
install -d -o "${TARGET_USER}" -g "${TARGET_GROUP}" "${TARGET_HOME}/.config/mpv"
MPV_CONF="${TARGET_HOME}/.config/mpv/mpv.conf"
if [[ -f ${MPV_CONF} ]]; then
    cp -n "${MPV_CONF}" "${MPV_CONF}.sonicfx-backup" || true
fi
cat > "${MPV_CONF}" <<'EOF'
# Generated by SonicFX Media 4K setup.
# Hardware video decoding through VA-API (Intel HD 620 friendly).
hwdec=vaapi
vo=gpu
gpu-api=opengl
# Keep audio as the master clock; avoids resample stutter on 24p films.
video-sync=audio
# Large cache helps when streaming 4K files over the network.
cache=yes
demuxer-max-bytes=512MiB
EOF
chown "${TARGET_USER}:${TARGET_GROUP}" "${MPV_CONF}"

# ---------------------------------------------------------------------------
# Firefox VA-API preferences (deb and snap profiles are both handled)
# ---------------------------------------------------------------------------
say "Enabling Firefox hardware video decoding (profiles found on this system)"
firefox_profiles=0
add_firefox_prefs() {
    local profile_dir="$1"
    local user_js="${profile_dir}/user.js"
    [[ -f ${user_js} ]] || cp -n "${user_js}" "${user_js}.sonicfx-backup" 2>/dev/null || true
    touch "${user_js}"
    if ! grep -q 'media\.ffmpeg\.vaapi\.enabled' "${user_js}"; then
        printf '%s\n' 'user_pref("media.ffmpeg.vaapi.enabled", true);' >> "${user_js}"
    fi
    if ! grep -q 'media\.hardware-video-decoding\.enabled' "${user_js}"; then
        printf '%s\n' 'user_pref("media.hardware-video-decoding.enabled", true);' >> "${user_js}"
    fi
    chown "${TARGET_USER}:${TARGET_GROUP}" "${user_js}" 2>/dev/null || true
}

while IFS= read -r -d '' profile_dir; do
    add_firefox_prefs "${profile_dir}"
    firefox_profiles=$((firefox_profiles + 1))
    echo "    configured: ${profile_dir}"
done < <(find "${TARGET_HOME}/.mozilla/firefox" \
              "${TARGET_HOME}/snap/firefox/common/.mozilla/firefox" \
              -maxdepth 2 -name prefs.js -printf '%h\0' 2>/dev/null)

if (( firefox_profiles == 0 )); then
    echo "    no Firefox profile yet (prefs will apply to future profiles via defaults below)"
fi

# Set the same prefs as system-wide defaults for the user's future profiles.
FIREFOX_DEFAULTS_DIR="${TARGET_HOME}/.mozilla/firefox"
if [[ -d ${FIREFOX_DEFAULTS_DIR} ]]; then
    cat > "${FIREFOX_DEFAULTS_DIR}/sonicfx-vaapi.js" <<'EOF'
// Loaded automatically by Firefox when present in the profile directory.
user_pref("media.ffmpeg.vaapi.enabled", true);
user_pref("media.hardware-video-decoding.enabled", true);
EOF
    chown "${TARGET_USER}:${TARGET_GROUP}" "${FIREFOX_DEFAULTS_DIR}/sonicfx-vaapi.js" 2>/dev/null || true
fi

# ---------------------------------------------------------------------------
# Verification
# ---------------------------------------------------------------------------
say "Verifying VA-API capabilities"
VA_LOG="$(mktemp)"
if sudo -u "${TARGET_USER}" env LIBVA_DRIVER_NAME=iHD vainfo 2>&1 | tee "${VA_LOG}" | head -25; then
    :
else
    echo "warning: vainfo failed; will retry without forcing iHD" >&2
    sudo -u "${TARGET_USER}" vainfo 2>&1 | tee "${VA_LOG}" | head -25 || true
fi

PANEL_MODE="$(head -1 /sys/class/drm/card*-eDP-1/modes 2>/dev/null | head -1 || true)"
PANEL_MODE="${PANEL_MODE:-unknown}"

printf '\n============================= Summary =============================\n'
if grep -q 'VAProfileHEVCMain10' "${VA_LOG}" 2>/dev/null; then
    echo "HEVC 10-bit 4K hardware decode : supported"
else
    echo "HEVC 10-bit 4K hardware decode : not reported (check vainfo output)"
fi
if grep -q 'VAProfileVP9Profile0' "${VA_LOG}" 2>/dev/null; then
    echo "VP9 (YouTube 4K) decode        : supported"
else
    echo "VP9 (YouTube 4K) decode        : not reported (check vainfo output)"
fi
if grep -q 'VAProfileAV1' "${VA_LOG}" 2>/dev/null; then
    echo "AV1 hardware decode            : supported"
else
    echo "AV1 hardware decode            : not supported on HD 620 (software only)"
fi
echo "Internal panel                 : ${PANEL_MODE}"
echo "Firefox profiles configured    : ${firefox_profiles}"
if command -v yt-dlp >/dev/null 2>&1; then
    echo "YouTube URL support            : yt-dlp $(yt-dlp --version)"
else
    echo "YouTube URL support            : MISSING — install yt-dlp" >&2
fi
echo
echo "Test a movie:"
echo "  mpv --hwdec=vaapi '/path/to/movie.mkv'      # press Ctrl+Shift+I for stats"
echo "  celluloid '/path/to/movie.mkv'"
echo
echo "Firefox: open about:support -> Graphics -> look for 'VA-API' + codec entries."
echo "Restart Firefox (and sign out/in once for Wayland) to pick up the prefs."
echo "=================================================================="
rm -f "${VA_LOG}"
