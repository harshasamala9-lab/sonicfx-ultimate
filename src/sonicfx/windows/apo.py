"""Equalizer APO configuration and safe include management.

Equalizer APO is the Windows real-time DSP backend.  It is a separate native
application (GPL-2.0), installed once by the user or by
``scripts/install-windows.ps1``.  This module only writes a small, generated
configuration file and keeps a single ``Include: sonicfx.txt`` line in
Equalizer APO's ``config.txt``.  Nothing here runs in an audio callback.

The generated syntax follows the official configuration reference:
https://sourceforge.net/p/equalizerapo/wiki/Configuration%20reference/
"""
from __future__ import annotations

import os
import shutil
import sys
import tempfile
from dataclasses import dataclass
from pathlib import Path

from sonicfx.dsp.filters import BiquadBand, FilterKind

__all__ = [
    "ApoError",
    "ApoStatus",
    "EqualizerApo",
    "INCLUDE_LINE",
    "INCLUDE_NAME",
    "render_apo_config",
]

INCLUDE_NAME = "sonicfx.txt"
INCLUDE_LINE = f"Include: {INCLUDE_NAME}"

_FILTER_TYPES = {
    FilterKind.PEAKING: "PK",
    FilterKind.LOW_SHELF: "LS",
    FilterKind.HIGH_SHELF: "HS",
    FilterKind.LOW_PASS: "LPQ",
    FilterKind.HIGH_PASS: "HPQ",
    FilterKind.BAND_PASS: "BP",
    FilterKind.NOTCH: "NO",
    FilterKind.ALL_PASS: "AP",
}

_SHAPED = frozenset(
    {FilterKind.PEAKING, FilterKind.LOW_SHELF, FilterKind.HIGH_SHELF}
)


class ApoError(RuntimeError):
    """A user-facing Equalizer APO configuration failure."""


@dataclass(frozen=True)
class ApoStatus:
    """Observed installation/configuration state (never an optimistic flag)."""

    installed: bool
    config_dir: Path | None
    config_file: Path | None
    include_active: bool
    include_file: Path | None = None
    configurator: Path | None = None
    detail: str = ""


def _number(value: float) -> str:
    """Stable, locale-independent number formatting for APO config lines."""
    text = f"{value:.3f}".rstrip("0").rstrip(".")
    return text or "0"


def _filter_line(index: int, band: BiquadBand) -> str:
    kind = _FILTER_TYPES.get(band.kind)
    if kind is None:  # pragma: no cover - exhaustive enum guard
        raise ApoError(f"Equalizer APO cannot render filter kind {band.kind!r}")
    parts = [f"Filter {index}: ON {kind}", f"Fc {_number(band.freq)} Hz"]
    if band.kind in _SHAPED:
        parts.extend([f"Gain {band.gain_db:+.1f} dB", f"Q {_number(band.q)}"])
    elif band.kind in {
        FilterKind.LOW_PASS,
        FilterKind.HIGH_PASS,
        FilterKind.BAND_PASS,
        FilterKind.NOTCH,
        FilterKind.ALL_PASS,
    }:
        parts.append(f"Q {_number(band.q)}")
    return " ".join(parts)


def render_apo_config(
    bands: tuple[BiquadBand, ...] | list[BiquadBand],
    *,
    preamp_db: float | None = None,
    source: str = "SonicFX Ultimate",
) -> str:
    """Render a complete ``sonicfx.txt`` for Equalizer APO.

    ``preamp_db`` defaults to the negative of the largest positive band gain,
    which is the simple headroom guard used by the Windows backend.  Pass an
    explicit value when a profile already contains its own headroom decision.
    """
    active = [band for band in bands if band.enabled]
    if preamp_db is None:
        positive = [band.gain_db for band in active if band.kind in _SHAPED]
        preamp_db = -max(0.0, max(positive, default=0.0))
    lines = [
        f"# Generated by {source} — do not edit by hand.",
        "# Equalizer APO is the native real-time DSP; Python is not in the audio path.",
        "# Enable the output devices you want in Equalizer APO's Device Selector.",
    ]
    if preamp_db < 0.0 or preamp_db > 0.0:
        lines.append(f"Preamp: {preamp_db:+.1f} dB")
    for index, band in enumerate(active, start=1):
        lines.append(_filter_line(index, band))
    return "\n".join(lines) + "\n"


def _read_text(path: Path) -> str:
    try:
        # utf-8-sig accepts an existing BOM (common when the user edited
        # config.txt in Notepad) and behaves like utf-8 otherwise.
        return path.read_text(encoding="utf-8-sig")
    except FileNotFoundError:
        return ""
    except UnicodeDecodeError:
        # Equalizer APO configs are normally ASCII/UTF-8, but an older editor
        # may have saved Windows-1252 comments. Read them so include detection
        # still works; the next SonicFX write is UTF-8 without a BOM.
        try:
            return path.read_text(encoding="cp1252")
        except OSError as exc:
            raise ApoError(f"could not read {path}: {exc}") from exc
    except OSError as exc:
        raise ApoError(f"could not read {path}: {exc}") from exc


def _has_include(text: str) -> bool:
    wanted = INCLUDE_LINE.casefold()
    return any(line.strip().casefold() == wanted for line in text.splitlines())


def _atomic_write(path: Path, text: str) -> None:
    """Write a config atomically so Equalizer APO never sees a partial file."""
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, temporary = tempfile.mkstemp(prefix=f".{path.name}.", dir=path.parent)
    tmp_path = Path(temporary)
    try:
        with os.fdopen(fd, "w", encoding="utf-8", newline="\n") as handle:
            handle.write(text)
            handle.flush()
            os.fsync(handle.fileno())
        os.replace(tmp_path, path)
    except OSError as exc:
        raise ApoError(f"could not write {path}: {exc}") from exc
    finally:
        tmp_path.unlink(missing_ok=True)


def _registry_config_dir() -> Path | None:
    """Read Equalizer APO's ConfigPath registry value on Windows."""
    if sys.platform != "win32":
        return None
    try:
        import winreg

        with winreg.OpenKey(
            winreg.HKEY_LOCAL_MACHINE, r"SOFTWARE\EqualizerAPO"
        ) as key:
            value, _kind = winreg.QueryValueEx(key, "ConfigPath")
    except (ImportError, OSError):
        return None
    text = str(value).strip()
    return Path(text) if text else None


def discover_config_dir() -> Path | None:
    """Locate Equalizer APO's writable configuration directory.

    ``SONICFX_APO_CONFIG_DIR`` wins for portable/test setups.  On Windows the
    official ``HKLM\\SOFTWARE\\EqualizerAPO\\ConfigPath`` value is authoritative;
    the conventional Program Files location is a fallback.
    """
    override = os.environ.get("SONICFX_APO_CONFIG_DIR", "").strip()
    if override:
        candidate = Path(override).expanduser()
        return candidate if candidate.is_dir() else None

    registry = _registry_config_dir()
    if registry is not None and registry.is_dir():
        return registry

    candidates: list[Path] = []
    for env_name in ("ProgramW6432", "ProgramFiles", "ProgramFiles(x86)"):
        base = os.environ.get(env_name)
        if base:
            candidates.append(Path(base) / "EqualizerAPO" / "config")
    candidates.append(Path(r"C:\Program Files\EqualizerAPO\config"))
    for candidate in candidates:
        if candidate.is_dir():
            return candidate
    return None


class EqualizerApo:
    """Manage one Equalizer APO configuration include.

    The user's existing ``config.txt`` is never replaced.  A backup is made the
    first time SonicFX adds its include, and disabling removes only the exact
    include line SonicFX added.
    """

    def __init__(
        self,
        config_dir: Path | str | None = None,
        config_file: Path | str | None = None,
    ) -> None:
        if config_file is not None:
            self.config_file = Path(config_file)
            self.config_dir = (
                Path(config_dir) if config_dir is not None else self.config_file.parent
            )
        elif config_dir is not None:
            self.config_dir = Path(config_dir)
            self.config_file = self.config_dir / "config.txt"
        else:
            discovered = discover_config_dir()
            self.config_dir = discovered
            self.config_file = discovered / "config.txt" if discovered else None
        self.include_file = (
            self.config_dir / INCLUDE_NAME if self.config_dir is not None else None
        )
        self.backup_file = (
            self.config_file.with_name(f"{self.config_file.name}.sonicfx-backup")
            if self.config_file is not None
            else None
        )

    # -- observation -------------------------------------------------------
    @property
    def installed(self) -> bool:
        return bool(self.config_dir is not None and self.config_dir.is_dir())

    @property
    def configurator(self) -> Path | None:
        """Path to the Equalizer APO device selector/configurator, if present."""
        if self.config_dir is None:
            return None
        roots = [self.config_dir.parent, self.config_dir]
        for root in roots:
            for name in ("DeviceSelector.exe", "Configurator.exe"):
                candidate = root / name
                if candidate.is_file():
                    return candidate
        return None

    def include_active(self) -> bool:
        if self.config_file is None:
            return False
        return _has_include(_read_text(self.config_file))

    def status(self) -> ApoStatus:
        if not self.installed:
            return ApoStatus(
                installed=False,
                config_dir=self.config_dir,
                config_file=self.config_file,
                include_active=False,
                include_file=self.include_file,
                configurator=self.configurator,
                detail=(
                    "Equalizer APO was not found. Install it once from "
                    "https://sourceforge.net/projects/equalizerapo/ and reboot."
                ),
            )
        try:
            active = self.include_active()
        except ApoError as exc:
            return ApoStatus(
                installed=True,
                config_dir=self.config_dir,
                config_file=self.config_file,
                include_active=False,
                include_file=self.include_file,
                configurator=self.configurator,
                detail=str(exc),
            )
        detail = (
            "SonicFX is included in Equalizer APO's config.txt."
            if active
            else "Equalizer APO is installed; SonicFX is not active."
        )
        return ApoStatus(
            installed=True,
            config_dir=self.config_dir,
            config_file=self.config_file,
            include_active=active,
            include_file=self.include_file,
            configurator=self.configurator,
            detail=detail,
        )

    # -- mutation ----------------------------------------------------------
    def apply(
        self,
        bands: tuple[BiquadBand, ...] | list[BiquadBand],
        *,
        preamp_db: float | None = None,
    ) -> ApoStatus:
        """Write the generated filters and activate the include atomically."""
        if not self.installed:
            raise ApoError(
                "Equalizer APO is not installed. Install it, reboot, then retry."
            )
        assert self.config_file is not None
        assert self.include_file is not None
        if not self.config_file.exists():
            _atomic_write(self.config_file, "# Equalizer APO configuration\n")
        _atomic_write(
            self.include_file,
            render_apo_config(bands, preamp_db=preamp_db),
        )
        self._activate_include()
        return self.status()

    def disable(self) -> ApoStatus:
        """Remove SonicFX's include while preserving the user's own config."""
        if self.config_file is not None and self.config_file.exists():
            original = _read_text(self.config_file)
            kept = [
                line
                for line in original.splitlines()
                if line.strip().casefold() != INCLUDE_LINE.casefold()
            ]
            if len(kept) != len(original.splitlines()):
                _atomic_write(self.config_file, "\n".join(kept).rstrip() + "\n")
        if self.include_file is not None and self.include_file.exists():
            _atomic_write(
                self.include_file,
                "# SonicFX Ultimate is disabled; start the app to re-enable it.\n",
            )
        return self.status()

    def _activate_include(self) -> None:
        assert self.config_file is not None
        original = _read_text(self.config_file)
        if _has_include(original):
            return
        if self.backup_file is not None and not self.backup_file.exists():
            try:
                shutil.copy2(self.config_file, self.backup_file)
            except OSError as exc:
                raise ApoError(f"could not back up {self.config_file}: {exc}") from exc
        suffix = "" if not original or original.endswith("\n") else "\n"
        addition = (
            f"{suffix}\n# Added by SonicFX Ultimate\n{INCLUDE_LINE}\n"
        )
        _atomic_write(self.config_file, original + addition)
